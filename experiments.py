from smolagents import DuckDuckGoSearchTool, HfApiModel, ToolCallingAgent, VisitWebpageTool, PromptTemplates
import os
from dotenv import load_dotenv

load_dotenv()

# ===============================================
# ЭКСПЕРИМЕНТ 1: Разные системные промпты
# ===============================================

print("="*60)
print("ЭКСПЕРИМЕНТ 1: Влияние системного промпта")
print("="*60)

# Базовый промпт (короткий)
basic_prompt = """
Ты - исследователь. Ищи информацию в интернете.
Используй DuckDuckGoSearchTool и VisitWebpageTool.
Когда найдёшь ответ, вызывай final_answer.
"""

# Детальный промпт (подробный)
detailed_prompt = """
Ты - профессиональный исследователь интернета.

ТВОЯ ЗАДАЧА:
Найти точную и достоверную информацию на вопрос пользователя.

ДОСТУПНЫЕ ИНСТРУМЕНТЫ:
1. DuckDuckGoSearchTool - поиск в интернете
   - Используй для первичного поиска информации
   - Возвращает до 5 результатов
   
2. VisitWebpageTool - чтение веб-страниц
   - Используй для детального изучения найденных страниц
   - Читает полный текст статьи

ПРАВИЛА РАБОТЫ:
- Если вопрос сложный, разбей его на части
- Всегда проверяй информацию из нескольких источников
- Если данные противоречивы, ищи дополнительные источники
- Читай полные статьи, не ограничивайся заголовками
- Особое внимание обращай на даты и цифры

ЗАВЕРШЕНИЕ:
Когда уверен в ответе, вызывай final_answer с найденной информацией.
"""

# Выберите промпт для тестирования:
test_prompt = detailed_prompt  # Измените на basic_prompt для сравнения

# ===============================================
# ЭКСПЕРИМЕНТ 2: Разные модели
# ===============================================

print("\n" + "="*60)
print("ЭКСПЕРИМЕНТ 2: Разные модели")
print("="*60)

# Список доступных моделей (раскомментируйте нужную)
models = {
    "qwen": "Qwen/Qwen2.5-72B-Instruct",           # Быстрая и качественная
    # "mixtral": "mistralai/Mixtral-8x7B-Instruct-v0.1",  # Очень быстрая
    # "llama": "meta-llama/Llama-3.1-70B-Instruct",      # Очень умная
}

selected_model = "qwen"  # Измените для тестирования другой модели

model = HfApiModel(
    model_id=models[selected_model],
    token=os.getenv("HF_TOKEN")
)

print(f"Используется модель: {models[selected_model]}")

# ===============================================
# ЭКСПЕРИМЕНТ 3: Разное количество max_steps
# ===============================================

print("\n" + "="*60)
print("ЭКСПЕРИМЕНТ 3: Влияние max_steps")
print("="*60)

# Попробуйте разные значения:
# - 5 (мало шагов - может не успеть найти ответ)
# - 10 (стандартное значение)
# - 15 (много шагов - более тщательный поиск)

max_steps_value = 10  # Измените для эксперимента

print(f"Максимум шагов: {max_steps_value}")

# ===============================================
# ЭКСПЕРИМЕНТ 4: Разные вопросы
# ===============================================

print("\n" + "="*60)
print("ЭКСПЕРИМЕНТ 4: Разные типы вопросов")
print("="*60)

questions = {
    "простой": "Когда родился Альберт Эйнштейн?",
    
    "многошаговый": "Найди название команды, которая заняла 3 место в TI10. В каком турнире произошел дебют этой команды?",
    
    "с_расчётами": "Сколько километров от Москвы до Владивостока?",
    
    "актуальный": "Кто сейчас президент США?",
    
    "сложный": "Сравни население трёх крупнейших городов России и назови разницу между первым и третьим",
}

# Выберите вопрос для тестирования:
question_type = "простой"  # Измените тип вопроса
query = questions[question_type]

print(f"Тип вопроса: {question_type}")
print(f"Вопрос: {query}")

# ===============================================
# ЗАПУСК АГЕНТА
# ===============================================

# Настройка инструментов
tools = [
    DuckDuckGoSearchTool(max_results=5),
    VisitWebpageTool()
]

# Создание промпта
prompt_template = PromptTemplates(system_prompt=test_prompt)

# Создание агента
agent = ToolCallingAgent(
    tools=tools,
    model=model,
    prompt_templates=prompt_template,
    max_steps=max_steps_value,
    verbosity_level=2  # 0=тихо, 1=базовая инфо, 2=детально
)

# Запуск
print("\n" + "="*60)
print("РЕЗУЛЬТАТ ЭКСПЕРИМЕНТА")
print("="*60 + "\n")

try:
    result = agent.run(query)
    print("\n" + "="*60)
    print("ОТВЕТ АГЕНТА:")
    print("="*60)
    print(result)
    
except Exception as e:
    print(f"Ошибка: {e}")

# ===============================================
# ЗАДАНИЯ ДЛЯ САМОСТОЯТЕЛЬНОЙ РАБОТЫ
# ===============================================

print("\n" + "="*60)
print("ЗАДАНИЯ ДЛЯ ЭКСПЕРИМЕНТОВ")
print("="*60)
