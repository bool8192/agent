"""
AI-Агент для поиска в интернете
Использует Hugging Face API и библиотеку smolagents
"""

from smolagents import (
    DuckDuckGoSearchTool,  # Инструмент для поиска в интернете
    HfApiModel,            # Модель от Hugging Face
    ToolCallingAgent,      # Агент, который может вызывать инструменты
    VisitWebpageTool,      # Инструмент для чтения веб-страниц
    PromptTemplates        # Шаблоны промптов
)
import os
from dotenv import load_dotenv

# Загружаем переменные окружения из файла .env
load_dotenv()

# ===== ШАГ 1: НАСТРОЙКА МОДЕЛИ =====
print("🤖 Настраиваем модель...")

# Используем модель Qwen от Hugging Face
# Это бесплатная модель, которая хорошо работает с инструментами
model = HfApiModel(
    model_id="Qwen/Qwen2.5-72B-Instruct",  # ID модели на Hugging Face
    token=os.getenv("HF_TOKEN")             # Ваш API токен
)

# ===== ШАГ 2: НАСТРОЙКА ИНСТРУМЕНТОВ =====
print("🔧 Настраиваем инструменты...")

# Список инструментов, которые может использовать агент
tools = [
    DuckDuckGoSearchTool(max_results=5),  # Поиск в интернете (до 5 результатов)
    VisitWebpageTool()                     # Чтение содержимого веб-страниц
]

# ===== ШАГ 3: СОЗДАНИЕ СИСТЕМНОГО ПРОМПТА =====
print("📝 Создаем системный промпт...")

# Системный промпт - это инструкция для агента
system_prompt = """
Ты - профессиональный исследователь интернета и ассистент пользователя.

Твоя задача - найти точную и достоверную информацию, которую запрашивает пользователь.

У тебя есть следующие инструменты:

1. DuckDuckGoSearchTool - используй его для поиска информации в интернете.
   Он возвращает список результатов с заголовками, описаниями и ссылками.

2. VisitWebpageTool - используй его для чтения содержимого конкретных веб-страниц.
   Передай ему URL страницы, которую нужно прочитать.

ВАЖНЫЕ ПРАВИЛА:

- Если вопрос состоит из нескольких частей, сначала найди ответ на первую часть,
  а затем используй эту информацию для поиска ответа на следующую часть.
  
- Всегда перепроверяй найденную информацию, делая дополнительные запросы
  или читая несколько источников.
  
- Если информация противоречива или неточна, продолжай поиск.

- Используй VisitWebpageTool для получения детальной информации со страниц,
  которые выглядят наиболее релевантными в результатах поиска.

Когда находишь окончательный ответ, вызывай инструмент final_answer и пиши в нём найденную информацию.
"""

# Создаем шаблон промпта
prompt_template = PromptTemplates(system_prompt=system_prompt)

# ===== ШАГ 4: СОЗДАНИЕ АГЕНТА =====
print("🚀 Создаем агента...")

agent = ToolCallingAgent(
    tools=tools,                      # Инструменты для агента
    model=model,                      # Языковая модель
    prompt_templates=prompt_template, # Системный промпт
    max_steps=10                      # Максимум шагов (защита от зацикливания)
)

# ===== ШАГ 5: ЗАПУСК АГЕНТА =====
print("\n" + "="*60)
print("AI-АГЕНТ ГОТОВ К РАБОТЕ!")
print("="*60 + "\n")

# Тестовые вопросы
test_queries = [
    "В каком году Кассиус Клей сменил имя?",
    "Какая команда заняла 3 место на The International 10 по Dota 2?",
    "Сколько времени занимает полет от Москвы до Владивостока?"
]

# Вы можете выбрать вопрос или написать свой
query = test_queries[0]  # Измените индекс [0] на [1] или [2] для других вопросов

# Или раскомментируйте следующую строку, чтобы ввести свой вопрос:
# query = input("Введите ваш вопрос: ")

print(f"❓ Вопрос: {query}\n")
print("🔄 Агент работает...\n")

# Запускаем агента
try:
    result = agent.run(query)
    print("\n" + "="*60)
    print("✅ РЕЗУЛЬТАТ:")
    print("="*60)
    print(result)
    
except Exception as e:
    print(f"\n❌ Ошибка: {e}")
    print("\nПроверьте:")
    print("1. Установлены ли библиотеки (см. requirements.txt)")
    print("2. Правильно ли указан HF_TOKEN в файле .env")
    print("3. Есть ли доступ к интернету")
